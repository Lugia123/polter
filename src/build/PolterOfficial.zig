//! What Polter ships as data: the official roles (`src/poltergeist/roles/`)
//! and the official skills (`src/poltergeist/skills/`).
//!
//! Two jobs, both done while the build is being configured:
//!
//!   * **List the two directories**, so that neither list is written out by
//!     hand anywhere. A role is added by adding its two files; a skill by
//!     adding its one.
//!   * **Read every file with the parser the program reads it with**, and
//!     fail the build on one that does not read. A test would catch the
//!     same mistake only in a build that compiles that test, and a build
//!     with `-Dtest-filter` compiles none but the ones it names -- so the
//!     check lives here, where every build passes through it.
//!
//! What comes out is a module, `polter_official`, that embeds the files. The
//! roles are used by the program (`official.zig`); the skills only by tests,
//! since the program reads those from the resources directory, where a
//! person can see them.
const PolterOfficial = @This();

const std = @import("std");
const official = @import("../poltergeist/official.zig");
const skill = @import("../poltergeist/skill.zig");

/// The generated Zig file.
output: std.Build.LazyPath,

const roles_dir = "src/poltergeist/roles";
const skills_dir = "src/poltergeist/skills";

pub fn init(b: *std.Build) !PolterOfficial {
    const wf = b.addWriteFiles();

    var src: std.Io.Writer.Allocating = .init(b.allocator);
    const w = &src.writer;
    try w.writeAll(
        \\//! This file is auto-generated by src/build/PolterOfficial.zig. Do not edit.
        \\
        \\pub const Role = struct { key: []const u8, json: []const u8, md: []const u8 };
        \\pub const Skill = struct { name: []const u8, source: []const u8 };
        \\
        \\pub const roles = [_]Role{
        \\
    );

    // --- roles: `<key>.json` and `<key>.md`, and nothing else.
    const role_files = try list(b, roles_dir);
    for (role_files) |name| {
        if (std.mem.endsWith(u8, name, ".md")) {
            const stem = name[0 .. name.len - ".md".len];
            if (!contains(role_files, b.fmt("{s}.json", .{stem})))
                return fail("{s}/{s} has no {s}.json beside it", .{ roles_dir, name, stem });
            continue;
        }
        if (!std.mem.endsWith(u8, name, ".json"))
            return fail("{s}/{s}: only <key>.json and <key>.md belong here", .{ roles_dir, name });

        const key = name[0 .. name.len - ".json".len];
        const md_name = b.fmt("{s}.md", .{key});
        if (!contains(role_files, md_name))
            return fail("{s}/{s} has no {s} beside it (the role's instructions)", .{ roles_dir, name, md_name });

        const json = try read(b, roles_dir, name);
        const md = try read(b, roles_dir, md_name);
        var arena: std.heap.ArenaAllocator = .init(b.allocator);
        defer arena.deinit();
        _ = official.parseSource(arena.allocator(), .{ .key = key, .json = json, .md = md }) catch |err|
            return fail("{s}/{s} does not read as an official role: {t}", .{ roles_dir, name, err });

        _ = wf.addCopyFile(b.path(b.pathJoin(&.{ roles_dir, name })), b.pathJoin(&.{ "roles", name }));
        _ = wf.addCopyFile(b.path(b.pathJoin(&.{ roles_dir, md_name })), b.pathJoin(&.{ "roles", md_name }));
        try w.print(
            "    .{{ .key = \"{s}\", .json = @embedFile(\"roles/{s}\"), .md = @embedFile(\"roles/{s}\") }},\n",
            .{ key, name, md_name },
        );
    }

    try w.writeAll("};\n\npub const skills = [_]Skill{\n");

    // --- skills: `<name>.md`, whose frontmatter names itself.
    for (try list(b, skills_dir)) |name| {
        if (!std.mem.endsWith(u8, name, ".md"))
            return fail("{s}/{s}: only <name>.md belongs here", .{ skills_dir, name });
        const stem = name[0 .. name.len - ".md".len];
        const source = try read(b, skills_dir, name);
        const parsed = skill.parse(source) catch |err|
            return fail("{s}/{s} does not read as a skill: {t}", .{ skills_dir, name, err });
        if (!std.mem.eql(u8, parsed.meta.name, stem))
            return fail("{s}/{s} names itself \"{s}\"; a skill's name is its file name", .{ skills_dir, name, parsed.meta.name });

        _ = wf.addCopyFile(b.path(b.pathJoin(&.{ skills_dir, name })), b.pathJoin(&.{ "skills", name }));
        try w.print(
            "    .{{ .name = \"{s}\", .source = @embedFile(\"skills/{s}\") }},\n",
            .{ stem, name },
        );
    }
    try w.writeAll("};\n");

    return .{ .output = wf.add("polter_official.zig", src.written()) };
}

/// Add the "polter_official" import.
pub fn addImport(self: *const PolterOfficial, step: *std.Build.Step.Compile) void {
    self.output.addStepDependencies(&step.step);
    step.root_module.addAnonymousImport("polter_official", .{
        .root_source_file = self.output,
    });
}

fn fail(comptime fmt: []const u8, args: anytype) error{BadOfficialData} {
    std.log.err(fmt, args);
    return error.BadOfficialData;
}

fn contains(names: []const []const u8, name: []const u8) bool {
    for (names) |n| {
        if (std.mem.eql(u8, n, name)) return true;
    }
    return false;
}

/// The files in `dir`, sorted, so the order things are embedded in does not
/// depend on the file system.
fn list(b: *std.Build, dir: []const u8) ![]const []const u8 {
    const io = b.graph.io;
    var d = try b.build_root.handle.openDir(io, dir, .{ .iterate = true });
    defer d.close(io);

    var names: std.ArrayList([]const u8) = .empty;
    var it = d.iterate();
    while (try it.next(io)) |entry| {
        if (entry.kind != .file) return fail("{s}/{s}: not a file", .{ dir, entry.name });
        // Editors and Finder leave these behind; they are not ours.
        if (entry.name[0] == '.') continue;
        try names.append(b.allocator, b.dupe(entry.name));
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn lt(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.lessThan(u8, x, y);
        }
    }.lt);
    return names.items;
}

fn read(b: *std.Build, dir: []const u8, name: []const u8) ![]const u8 {
    return try b.build_root.handle.readFileAlloc(
        b.graph.io,
        b.pathJoin(&.{ dir, name }),
        b.allocator,
        .limited(1024 * 1024),
    );
}
